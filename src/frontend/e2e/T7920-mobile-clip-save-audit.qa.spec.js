test('mobile clip-save live-drive audit (320x568 + 375x667)', async ({ page }) => {
  step('setupAuthedGuest start');
  await setupAuthedGuest(page);
  step('setupAuthedGuest done');
  await page.setViewportSize({ width: 375, height: 667 });
  await uploadGameAndEnterAnnotate(page);

  const savedClipIds = [];

  for (const vp of PORTRAIT_VIEWPORTS) {
    await page.setViewportSize({ width: vp.width, height: vp.height });
    await page.waitForTimeout(300);

    const form = await openMobileAddClipForm(page, SEEK_BY_VIEWPORT[vp.name]);

    // --- Criterion 1: form fully reachable/operable, no horizontal overflow ----
    await assertNoHorizontalOverflow(page);
    const saveBtn = form.locator('button.bg-green-600:has-text("Save")');
    await expect(saveBtn).toBeVisible();
    // Save control must be within the viewport (scrollable to; not clipped off).
    await saveBtn.scrollIntoViewIfNeeded();
    const saveBox = await saveBtn.boundingBox();
    expect(saveBox, 'Save button has a layout box').not.toBeNull();
    expect(saveBox.y).toBeGreaterThanOrEqual(0);
    expect(saveBox.y + saveBox.height).toBeLessThanOrEqual(vp.height + 1);
    await saveEvidence(page, `criterion-1-form-reachable-${vp.name}`);

    // --- Criterion 3: NoSportTagWarning renders in the Tags block --------------
    // A fresh guest profile is no_sport (T7850) -> the amber prompt replaces the
    // sport TagSelector. If a sport WAS chosen this asserts nothing false — we
    // record which branch actually rendered.
    // T7922: the full (portrait) no_sport prompt is now the ACTIONABLE inline
    // sport picker ("Pick your sport to tag this clip" + a Change-sport select),
    // not the old dead "top bar" prose. The compact landscape variant (asserted
    // later) still shows the instructional prose (deferred).
    const noSportWarn = form.getByText('Pick your sport to tag this clip');
    const hasNoSport = await noSportWarn.isVisible().catch(() => false);
    expect(hasNoSport, 'fresh guest should hit the no_sport inline sport picker branch').toBeTruthy();
    await saveEvidence(page, `criterion-3-nosport-warning-${vp.name}`);

    // --- Criterion 2: teammate tag typed WITHOUT Enter must not dead-end Save --
    // Teammates are Team-layer only, so switch the clip to Team to reveal the input.
    await form.getByRole('radio', { name: 'Team layer' }).click();
    const tagInput = form.getByPlaceholder('Tag a teammate...');
    await expect(tagInput).toBeVisible({ timeout: 5000 });
    const PENDING_TAG = `QA T7920 ${vp.name}`;
    await tagInput.fill(PENDING_TAG); // deliberately NO Enter — the trap condition
    // Criterion 4 (keyboard proxy): with the tag input focused (soft keyboard would
    // be up on a real phone), the Save button must still be reachable.
    await saveBtn.scrollIntoViewIfNeeded();
    await saveEvidence(page, `criterion-2-4-pending-tag-focused-${vp.name}`);

    // --- Criterion 4: Save round-trip completes, tag auto-committed ------------
    const [saveResp] = await Promise.all([
      page.waitForResponse(
        (r) => r.url().includes('/api/clips/raw/save') && r.request().method() === 'POST',
        { timeout: 15000 },
      ),
      saveBtn.click(),
    ]);
    expect(saveResp.ok(), `save POST ok at ${vp.name}`).toBeTruthy();
    const body = await saveResp.json();
    expect(body.raw_clip_id, `raw_clip_id returned at ${vp.name}`).toBeTruthy();
    savedClipIds.push(body.raw_clip_id);

    // T7540 on mobile: the pending (un-Entered) teammate text was auto-committed.
    const sent = saveResp.request().postDataJSON();
    if (gameId === undefined) gameId = sent.game_id; // robust gameId source
    expect(sent.tagged_teammates, `pending tag auto-committed at ${vp.name}`).toContain(PENDING_TAG);
    // The old OK-only dead-end dialog must never appear.
    await expect(page.getByText('Tag not submitted')).toHaveCount(0);
    await saveEvidence(page, `criterion-4-saved-${vp.name}`);
  }

  // --- Criterion 4 (durable proof): the raw_clips rows really exist ------------
  const loadRes = await page.request.get(`${apiBase}/games/${gameId}/load`);
  expect(loadRes.ok()).toBeTruthy();
  const loaded = await loadRes.json();
  const annotations = loaded.game?.annotations || loaded.annotations || [];
  const rawIds = new Set(annotations.map((a) => a.rawClipId ?? a.raw_clip_id ?? a.id));
  for (const id of savedClipIds) {
    expect([...rawIds].map(String), 'saved clip present in /load annotations').toContain(String(id));
  }
  console.log(`[T7920] saved raw_clip ids: ${savedClipIds.join(', ')}; /load annotations: ${annotations.length}`);

  // --- Criterion 3 (compact variant): landscape-inline NoSportTagWarning -------
  // The compact amber prompt only renders in the mobile-fullscreen LANDSCAPE scrub
  // bar (AnnotateFullscreenOverlay layout="landscape-inline"). annotateFullscreen
  // is CSS-based app state (no browser Fullscreen API), so it drives headless.
  await page.setViewportSize({ width: 667, height: 375 }); // landscape phone
  await page.waitForTimeout(300);
  // BEST-EFFORT: the landscape-fullscreen scrub bar auto-hides its controls, which
  // makes the NONE-state Add Clip button flaky to reach under emulation. The
  // compact NoSportTagWarning is component-tested; this live attempt is a bonus, so
  // a miss is logged (real-device gap) rather than failing the core audit.
  let compactVerified = false;
  const fsBtn = page.locator('button[title="Fullscreen"]:visible').first();
  if (await fsBtn.isVisible({ timeout: 2000 }).catch(() => false)) {
    await fsBtn.click({ timeout: 3000 }).catch(() => {});
    await page.waitForTimeout(500);
    const addBtnFs = page.locator('button[title="Add clip ending at current time (A)"]:visible').first();
    for (const t of [33, 15, 25, 45]) {
      await page.locator('video').first().evaluate((v, tt) => { if (!v.paused) v.pause(); v.currentTime = tt; }, t).catch(() => {});
      // Tap the video to reveal the auto-hiding fullscreen controls (bounded so a
      // fullscreen actionability stall can never hang the suite).
      await page.locator('video').first().click({ position: { x: 40, y: 30 }, timeout: 2500 }).catch(() => {});
      await page.waitForTimeout(400);
      if (await addBtnFs.isVisible({ timeout: 1000 }).catch(() => false)) {
        await addBtnFs.click({ timeout: 2500 }).catch(() => {});
        break;
      }
    }
    const lsForm = page.locator('[data-add-clip-form]:visible');
    if (await lsForm.getByText('Set your sport (top bar) for tags').isVisible({ timeout: 3000 }).catch(() => false)) {
      await assertNoHorizontalOverflow(page);
      await saveEvidence(page, 'criterion-3-nosport-warning-compact-landscape-667x375');
      compactVerified = true;
    }
  }
  console.log(compactVerified
    ? '[T7920] landscape-inline compact NoSportTagWarning verified live'
    : '[T7920] NOTE: compact NoSportTagWarning not driven under emulation (auto-hiding fullscreen controls) — covered by component tests; needs a real-device pass');
});
