/** Isolate a disposable authenticated guest (headers + test-login + auth gate). */
async function setupAuthedGuest(page) {
  await page.setExtraHTTPHeaders({ 'X-User-ID': TEST_USER_ID, 'X-Test-Mode': 'true' });
  // R2 presigned PUT/GET must not carry X-Test-Mode (CORS preflight).
  await page.route(/r2\.cloudflarestorage\.com/, async (route) => {
    const headers = { ...route.request().headers() };
    delete headers['x-test-mode'];
    await route.continue({ headers });
  });
  // Use domcontentloaded, NOT the default 'load': the SPA bootstrap keeps a
  // fetch in flight (checkAdmin / prefetch), so the window 'load' event can lag
  // indefinitely and a default goto/reload would hang to the test timeout.
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await page.evaluate(async () => {
    await fetch('/api/auth/test-login', {
      method: 'POST',
      credentials: 'include',
      headers: { 'Content-Type': 'application/json', 'X-Test-Mode': 'true' },
    });
  });
  // Bypass the frontend auth gate so requireAuth() runs the Add Clip action
  // instead of popping the login modal (faithful to an AUTHENTICATED mobile user).
  await page.evaluate(async () => {
    const { useAuthStore } = await import('/src/stores/authStore.js');
    useAuthStore.setState({ isAuthenticated: true, email: 't7920@e2e.local', showAuthModal: false });
  });
  await page.reload({ waitUntil: 'domcontentloaded' });
  // Wait for the home to hydrate (the Add Game entry point renders).
  await expect(page.locator('button:has-text("Add Game")').first()).toBeVisible({ timeout: 20000 });
}

const step = (m) => console.log(`[T7920:step] ${m}`);

/** Upload the short test video via the Add Game modal, land in Annotate. */
async function uploadGameAndEnterAnnotate(page) {
  // Games tab is best-effort (a zero-games home may not surface it); the top-level
  // "Add Game" CTA is the reliable entry point.
  step('click Games tab (best-effort)');
  await page.locator('button:has-text("Games")').first().click({ timeout: 3000 }).catch(() => {});
  await page.waitForTimeout(300);
  step('click Add Game');
  await page.locator('button:has-text("Add Game")').first().click();
  await openGameDetailsDisclosure(page);
  await expect(page.getByPlaceholder('e.g., Carlsbad SC')).toBeVisible({ timeout: 8000 });
  step('Add Game modal open');

  await page.getByPlaceholder('e.g., Carlsbad SC').fill('T7920 Audit');
  const today = new Date().toISOString().split('T')[0];
  await page.locator('input[type="date"]').fill(today);
  await page.getByRole('button', { name: 'Home' }).click({ force: true });

  const videoInput = page.locator('form input[type="file"][accept*="video"]');
  await expect(videoInput).toBeAttached({ timeout: 10000 });
  step('setInputFiles video');
  await videoInput.setInputFiles(TEST_VIDEO);
  await page.waitForTimeout(500);
  // Neutralize the client-side upload paywall: an isolated test guest has 0
  // credits and does NOT get the real-user starter grant, so once the balance
  // loads GameDetailsModal.handleSubmit opens Buy Credits instead of creating the
  // game (the backend still authorizes the guest upload — proven live). Seeding a
  // high balance keeps the drive on the create path deterministically. This is a
  // HARNESS-only bypass of a real-user affordance, not under test here.
  await page.evaluate(async () => {
    const { useCreditStore } = await import('/src/stores/creditStore.js');
    useCreditStore.setState({ balance: 1_000_000, loaded: true });
  });
  // The submit button is the LAST "Add Game" button in the modal footer; scope to
  // the enabled one and bound the click so a mid-transition relabel can't hang the
  // whole test. Fall back to submitting the form via Enter.
  const createButton = page.locator('form button:has-text("Add Game")').last();
  await expect(createButton).toBeEnabled({ timeout: 8000 });
  step('click Create (submit Add Game)');
  const clicked = await createButton.click({ timeout: 12000 }).then(() => true).catch(() => false);
  if (!clicked) {
    step('submit click did not settle; retry force + Enter');
    await createButton.click({ force: true, timeout: 8000 }).catch(() => {});
    await page.getByPlaceholder('e.g., Carlsbad SC').press('Enter').catch(() => {});
  }
  step('submitted; waiting for annotate video to mount');
  // gameId is read later from the first clip-save payload (game_id) — more robust
  // than racing a specific create-request response shape.

  // Wait for the annotate <video> to mount and become seekable.
  await expect(async () => {
    const video = page.locator('video').first();
    await expect(video).toBeVisible();
    expect(await video.evaluate((v) => !!v.src)).toBeTruthy();
  }).toPass({ timeout: 120000, intervals: [1000, 2000, 5000] });

  // Do NOT block on the R2 upload finalizing: the game_id exists from
  // onGameCreated mid-upload and save_raw_clip tolerates a still-pending file
  // (T1540 annotate-during-upload) — the local blob <video> is already seekable.
  // This mirrors mostafaali452010's real flow (add_clip_opened right after the
  // upload landed) and keeps the drive fast/deterministic instead of hostage to
  // variable in-container R2 finalize latency. Give it a short grace only.
  const uploadingButton = page.locator('button:has-text("Uploading video")');
  await page.waitForTimeout(2000);
  await uploadingButton.isVisible().then((v) => v && expect(uploadingButton).toBeHidden({ timeout: 30000 }).catch(() => {})).catch(() => {});

  step('video visible; waiting for seekable');
  await page.waitForFunction(() => {
    const v = document.querySelector('video');
    return !!v && v.readyState >= 2 && v.seekable.length > 0 && v.duration > 0;
  }, undefined, { timeout: 120000 });
  step('video seekable — annotate ready');
}

/**
 * Open the mobile inline Add Clip form. The non-fullscreen "Add Clip" button
 * renders ONLY in the NONE selection state; when the playhead sits inside a clip
 * the sidebar edits it and the button hides. The shared dev profile can carry
 * pre-existing clips, so scan candidate seek times (preferring the caller's) until
 * the playhead lands in a clip-free gap and the button shows.
 */
async function openMobileAddClipForm(page, preferredSeek) {
  const candidates = [preferredSeek, 78, 70, 62, 33, 15, 85, 8];
  const addBtn = page.locator('button[title="Add clip ending at current time (A)"]:visible').first();
  for (const t of candidates) {
    const landed = await page.locator('video').first().evaluate((v, tt) => {
      if (!v.paused) v.pause();
      v.currentTime = tt;
      return v.currentTime;
    }, t);
    if (Math.abs(landed - t) > 2) { await page.waitForTimeout(400); continue; }
    await page.waitForTimeout(700); // auto-select re-evaluates (deselects in a gap)
    if (await addBtn.isVisible().catch(() => false)) {
      await addBtn.click();
      const form = page.locator('[data-add-clip-form]:visible');
      await expect(form).toBeVisible({ timeout: 5000 });
      return form;
    }
  }
  throw new Error('[T7920] no clip-free gap found to open the mobile Add Clip form');
}

