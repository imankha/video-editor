// T17840 C1: the Earlier highlights section says, without any click, that
// highlights made from several plays are no longer supported for editing.
describe('T17840: Earlier highlights notice', () => {
  beforeEach(() => {
    window.history.replaceState(null, '', '/home');
    useGalleryStore.setState({ isOpen: false });
  });

  it('states plainly that several-play highlights are no longer supported', () => {
    renderManager({ projects: [{ id: 1, name: 'Old Reel', game_ids: [], is_auto_created: false, clip_count: 5 }] });
    fireEvent.click(screen.getByRole('button', { name: /^Plays/i }));
    const group = screen.getByTestId('legacy-reel-drafts');
    expect(within(group).getByText(/Highlights made from several plays are no longer supported for editing\./)).toBeTruthy();
    expect(group.textContent).not.toMatch(/clip|focus/i);
  });
});
